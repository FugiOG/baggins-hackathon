# Определение функции по частям
print("Функция f(x) определена как:")
print("f(x) = {")
print("  (e^x + ax - 1)/x,     если x < 0")
print("  b,                    если x = 0") 
print("  ln(1 + x)/√x,         если x > 0")
print("}")
print()

print("Для непрерывности в точке x = 0 необходимо:")
print("lim(x→0⁻) f(x) = lim(x→0⁺) f(x) = f(0) = b")
print()

# Вычисляем левосторонний предел
print("1. Левосторонний предел (x → 0⁻):")
print("lim(x→0⁻) (e^x + ax - 1)/x")
print()
print("Имеем неопределенность вида 0/0.")
print("Используем разложение e^x в ряд Тейлора:")
print("e^x = 1 + x + x²/2! + x³/3! + ... = 1 + x + x²/2 + x³/6 + ...")
print()
print("Подставляем:")
print("e^x + ax - 1 = (1 + x + x²/2 + x³/6 + ...) + ax - 1")
print("             = x + ax + x²/2 + x³/6 + ...")
print("             = x(1 + a) + x²/2 + x³/6 + ...")
print()
print("Тогда:")
print("(e^x + ax - 1)/x = (1 + a) + x/2 + x²/6 + ...")
print()
print("При x → 0⁻:")
print("lim(x→0⁻) f(x) = 1 + a")
print()

# Вычисляем правосторонний предел  
print("2. Правосторонний предел (x → 0⁺):")
print("lim(x→0⁺) ln(1 + x)/√x")
print()
print("Имеем неопределенность вида 0/0.")
print("Используем разложение ln(1 + x) в ряд Тейлора:")
print("ln(1 + x) = x - x²/2 + x³/3 - x⁴/4 + ...")
print()
print("Подставляем:")
print("ln(1 + x)/√x = (x - x²/2 + x³/3 - ...)/√x")
print("             = x/√x - x²/(2√x) + x³/(3√x) - ...")
print("             = √x - x·√x/2 + x²·√x/3 - ...")
print()
print("При x → 0⁺:")
print("lim(x→0⁺) f(x) = lim(x→0⁺) √x = 0")
print()

# Условия непрерывности
print("3. Условия непрерывности в точке x = 0:")
print("Для непрерывности необходимо:")
print("lim(x→0⁻) f(x) = lim(x→0⁺) f(x) = f(0)")
print()
print("Подставляем найденные пределы:")
print("1 + a = 0 = b")
